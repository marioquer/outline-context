/**
 * Runs every deterministic benchmark and writes benchmarks/results/RESULTS.md.
 *
 *   pnpm bench
 *
 * The LLM-graded runner is separate and opt-in (`pnpm bench:llm`).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { runRoutingBenchmark } from './routing.ts';
import { runContextBenchmarks } from './context.ts';
import { runSwitchingBenchmark } from './switching.ts';
import { RESULTS_DIR, gitCommit } from '../lib.ts';

const routing = await runRoutingBenchmark();
const context = await runContextBenchmarks();
const switching = await runSwitchingBenchmark();

const optional = (file: string, fallback: string) => {
  try {
    return readFileSync(join(RESULTS_DIR, file), 'utf8');
  } catch {
    return fallback;
  }
};
const jev = optional(
  'routing-jev.md',
  '### Benchmark E — Routing with real Jev\n\nNot run yet. Run `AI_GATEWAY_API_KEY=... pnpm bench:jev` to score typesafe-ai/jev on the same fixtures.',
);
const decisions = optional(
  'routing-openai-decisions.md',
  '### Benchmark E — Routing with OpenAI Decisions\n\nNot run yet. Run `OPENAI_API_KEY=... JEV_BACKEND=openai pnpm bench:jev` to score the same questions on OpenAI\'s Decisions API.',
);
const calibration = optional(
  'routing-calibration.md',
  '### Calibration — fork bias and route wording\n\nNot run yet. Run `pnpm bench:calibrate` with AI_GATEWAY_API_KEY and/or OPENAI_API_KEY set.',
);
const calibrationHoldout = optional(
  'routing-calibration-holdout.md',
  '### Calibration — held-out set\n\nNot run yet. Run `ROUTING_SET=holdout pnpm bench:calibrate`.',
);
const llm = optional(
  'llm-answers.md',
  '### LLM-graded answers\n\nNot run yet. Run `ANTHROPIC_API_KEY=... pnpm bench:llm` to grade real model answers.',
);

const doc = [
  '# Benchmark results',
  '',
  `Generated by \`pnpm bench\` at commit \`${gitCommit()}\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
  '',
  'Token counts are estimates (≈4 characters per token). "Fact in context" checks what the model would be shown, not what it answers. Cache numbers in Benchmark C are simulated from documented caching rules.',
  '',
  context.md,
  '',
  switching.md,
  '',
  routing.md,
  '',
  jev,
  '',
  decisions,
  '',
  calibration,
  '',
  calibrationHoldout,
  '',
  llm,
  '',
].join('\n');
writeFileSync(join(RESULTS_DIR, 'RESULTS.md'), doc);
console.log(doc);
